def _metadata_for(adapter: MidasAdapter, *, version_range: str = ">=2024") -> AdapterMetadata:
    """§15 metadata without awaiting ``adapter.metadata()``.

    ``register()`` is synchronous and ``metadata()`` is a coroutine (V2.1 §13 vs
    §21 — see ``AdapterRegistry``'s docstring), so the metadata is assembled here
    from the three §13 properties.  It is identical to what the async
    ``metadata()`` returns for both shipped adapters.
    """
    return AdapterMetadata(
        code=adapter.code,
        name=f"{adapter.software} Adapter",
        software=adapter.software,
        version_range=version_range,
        protocol="http" if isinstance(adapter, MidasNxAdapter) else "memory",
        supports_query=True,
        supports_model=True,
        supports_execute=True,
        # 对接规范 §2.5.1: MIDAS has no async task API — the platform's Task
        # Engine provides it (V2.1 §26).
        supports_async_task=True,
        capabilities=[capability.code for capability in CAPABILITIES],
    )


def register_configured_adapters(
    registry: AdapterRegistry,
    config: MidasConfig | None = None,
) -> list[str]:
    """Register one adapter per enabled entry of ``config/midas.json``.

    Returns the registered adapter codes.  Raises
    :class:`~app.core.midas_config.MidasConfigError` when the config file is
    missing or malformed — the caller decides whether that is fatal.
    """
    resolved = config if config is not None else load_midas_config()
    codes: list[str] = []
    for connection in resolved.enabled:
        adapter = MidasNxAdapter(connection)
        registry.register(adapter, metadata=_metadata_for(adapter), replace=True)
        codes.append(adapter.code)
    return codes


def register_mock_adapter(
    registry: AdapterRegistry, *, code: str = "midas_gen"
) -> str:
    """Register the in-memory adapter (V2.1 §22) under a real adapter code.

    Only for local development and tests: the mock answers fabricated data, so it
    is never registered implicitly (``main()`` requires ``--allow-mock``).
    """
    adapter = MockAdapter(code=code, software="MIDAS Gen")
    registry.register(
        adapter, metadata=_metadata_for(adapter, version_range=">=2024"), replace=True
    )
    return adapter.code


