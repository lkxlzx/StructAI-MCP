# ---------------------------------------------------------------------------
# SDK-side enums, generated from the capability table (V2.1 §6.1 / 总纲 §0.4)
# ---------------------------------------------------------------------------
_QUERY_TARGETS = Literal[tuple(resources_for(TOOL_QUERY))]
_QUERY_ACTIONS = Literal[tuple(actions_for(TOOL_QUERY))]

_MODEL_RESOURCES = Literal[tuple(resources_for(TOOL_MODEL))]
_MODEL_ACTIONS = Literal[tuple(actions_for(TOOL_MODEL))]

_EXECUTE_RESOURCES = Literal[tuple(resources_for(TOOL_EXECUTE))]
_EXECUTE_ACTIONS = Literal[tuple(actions_for(TOOL_EXECUTE))]

_TASK_ACTIONS = Literal[tuple(actions_for(TOOL_TASK))]
#: V2.1 §26.2 / 总纲 §4.2.1 — closed vocabularies, owned by app.core.constants.
_TASK_TYPES = Literal[tuple(task_type_values())]
_TASK_STATUSES = Literal[tuple(task_status_values())]


def _present(payload: dict[str, Any]) -> dict[str, Any]:
    """Drop ``None`` values before dispatching.

    The SDK hands the handler **every** declared parameter, filling omitted ones
    with their default (``None``).  Forwarding those Nones would put
    ``"page": null`` in front of the dispatcher's schema validation, where
    ``{"type": "integer", "minimum": 1}`` rightly rejects it.  Dropping them
    restores "the client sent only what it sent".
    """
    return {key: value for key, value in payload.items() if value is not None}


