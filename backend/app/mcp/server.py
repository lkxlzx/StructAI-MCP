def main(argv: Sequence[str] | None = None) -> int:
    """``python -m app.mcp.server --transport stdio|http``."""
    parser = argparse.ArgumentParser(
        prog="python -m app.mcp.server",
        description="StructAI MIDAS MCP server (V2.1 §7–§10).",
    )
    parser.add_argument(
        "--transport",
        choices=("stdio", "http"),
        default="stdio",
        help="stdio for local agents; http serves streamable HTTP at --path (default /mcp).",
    )
    parser.add_argument("--host", default=DEFAULT_HTTP_HOST)
    parser.add_argument("--port", type=int, default=DEFAULT_HTTP_PORT)
    parser.add_argument(
        "--path",
        default=MCP_HTTP_PATH,
        help="streamable HTTP path; v1.2 §37 keeps it separate from /api/v1.",
    )
    parser.add_argument(
        "--allow-mock",
        action="store_true",
        help=(
            "register the in-memory mock adapter when no MIDAS config is available "
            "(development only — it answers fabricated data)."
        ),
    )
    args = parser.parse_args(list(argv) if argv is not None else None)

    registry = get_registry()
    try:
        codes = register_configured_adapters(registry)
    except MidasConfigError as exc:
        codes = []
        print(f"[structai-mcp] {exc}", file=sys.stderr)

    if not codes:
        if not args.allow_mock:
            print(
                "[structai-mcp] 没有可用的 MIDAS adapter。请先配置 "
                "backend/config/midas.json（模板见 config/midas.example.json），"
                "或显式传 --allow-mock 使用内存 Mock（会返回伪造数据）。",
                file=sys.stderr,
            )
            return 2
        codes = [register_mock_adapter(registry)]
        print(
            f"[structai-mcp] --allow-mock：已注册内存 Mock adapter {codes[0]!r}；"
            "所有应答都是伪造的。",
            file=sys.stderr,
        )

    server = build_server(registry=registry)
    if args.transport == "stdio":
        server.run(transport="stdio")
    else:
        print(
            f"[structai-mcp] streamable HTTP on http://{args.host}:{args.port}{args.path}",
            file=sys.stderr,
        )
        server.run(
            transport="streamable-http",
            host=args.host,
            port=args.port,
            streamable_http_path=args.path,
        )
    return 0


if __name__ == "__main__":  # pragma: no cover - process entry point
    raise SystemExit(main())
