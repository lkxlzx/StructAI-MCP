#: ``(tool module, handler factory)`` in v1.2 §37 declaration order.
_TOOL_SPECS: Final[tuple[tuple[Any, Callable[[ToolDispatcher], Callable[..., Any]]], ...]] = (
    (query_tool, _make_query_handler),
    (model_tool, _make_model_handler),
    (execute_tool, _make_execute_handler),
    (task_tool, _make_task_handler),
)


def _publish_authoritative_schema(tool: Tool, schema: dict[str, Any]) -> None:
    """Install the schema generated from the capability table.

    See the module docstring: the SDK-derived schema omits
    ``additionalProperties``, which V2.1 §6.1 / 裁决 B-4 forbid.  The installed
    object is the *same* schema the dispatcher validates against, so the client
    contract and the server check cannot disagree (总纲 §0.4).
    """
    tool.parameters = dict(schema)


def build_tools(dispatcher: ToolDispatcher) -> list[Tool]:
    """Build the four tools, each with its authoritative published schema."""
    tools: list[Tool] = []
    for module, factory in _TOOL_SPECS:
        handler = factory(dispatcher)
        tool = Tool.from_function(
            handler,
            name=module.TOOL_NAME,
            description=module.DESCRIPTION,
            # Unstructured output: the envelope is returned as JSON text, which is
            # what every MCP client reads.  Publishing an outputSchema for a
            # hand-shaped envelope would add a second contract to keep in sync.
            structured_output=False,
        )
        _publish_authoritative_schema(tool, module.SCHEMA)
        tools.append(tool)
    return tools


def build_server(
    *,
    name: str = SERVER_NAME,
    version: str = SCHEMA_VERSION,
    registry: AdapterRegistry | None = None,
    dispatcher: ToolDispatcher | None = None,
    task_service: TaskService | None = None,
    authorizer: Any = None,
) -> MCPServer:
    """Build the MCP server exposing exactly the four V2.1 tools.

    The registry is **not** populated here: registration is the Service layer's
    job (V2.1 §21 + §15 落库映射).  Use :func:`register_configured_adapters` (or
    :func:`register_mock_adapter`) first, or pass a pre-populated ``registry``.
    """
    resolved_registry = registry if registry is not None else get_registry()
    resolved_tasks = task_service if task_service is not None else get_task_service()
    resolved_dispatcher = dispatcher or ToolDispatcher(
        registry=resolved_registry,
        task_service=resolved_tasks,
        authorizer=authorizer,
    )
    return MCPServer(
        name=name,
        title="StructAI MIDAS MCP Server",
        description=(
            "StructAI 平台的 MIDAS 工程能力 MCP 服务：midas_query / midas_model / "
            "midas_execute / midas_task（V2.1 §7–§10）。"
        ),
        instructions=INSTRUCTIONS,
        version=version,
        tools=build_tools(resolved_dispatcher),
    )


