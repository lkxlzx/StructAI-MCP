"""MCP server — v1.2 §37 (endpoint) / V2.1 §6–§11 (the four tools).

Two transports, exactly as 总纲/v1.2 require:

* **stdio** for local agents (``python -m app.mcp.server --transport stdio``);
* **streamable HTTP at ``/mcp``** for network clients
  (``python -m app.mcp.server --transport http``).  v1.2 §37: 「REST 管理 API 与
  MCP Protocol Endpoint 必须分离」 — ``/api/v1/*`` is management, ``/mcp`` is MCP,
  and the two envelopes must never be mixed (总纲 §4.3.2).

Schema publication (总纲 §0.4 唯一真源)
--------------------------------------
``MCPServer`` derives each tool's published ``inputSchema`` from the handler's
signature.  A **flat** signature — which is what the MCP protocol surface needs —
produces enums (from ``Literal``) but emits **no** ``additionalProperties`` key at
all, i.e. it is permissive.  V2.1 §6.1 / 裁决 B-4 require
``additionalProperties: false`` at every layer, so the authoritative schema
generated by :mod:`app.mcp.capabilities` is installed on each tool before the
server is built.  One schema object therefore serves both jobs: what the client
sees, and what the dispatcher validates against (see
:func:`app.mcp.dispatcher.validate_arguments`).

The handlers keep their ``Literal`` enums as well.  They are not redundant: they
are the SDK-side first line (a bad enum value is refused by pydantic before any
of our code runs), and they keep the signature self-documenting.
"""

